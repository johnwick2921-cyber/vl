package main

import (
	"fmt"
	"sort"
	"strings"

	"vl/kernel/pep"
)

type tally struct {
	traded, wins, losses, flat int
	gross                      float64 // points, per contract
	byExit                     map[pep.ExitKind]int
	refusals                   map[string]int
	bothEdges                  int
}

func tallyOf(ls []dayLine) tally {
	t := tally{byExit: map[pep.ExitKind]int{}, refusals: map[string]int{}}
	for _, l := range ls {
		if l.Mine.BothEdges {
			t.bothEdges++
		}
		if !l.Mine.Traded {
			if !l.NoData && l.Mine.Refusal != "" {
				t.refusals[l.Mine.Refusal]++
			}
			continue
		}
		t.traded++
		t.gross += l.Mine.GrossPts
		t.byExit[l.Mine.ExitKind]++
		switch {
		case l.Mine.GrossPts > 0:
			t.wins++
		case l.Mine.GrossPts < 0:
			t.losses++
		default:
			t.flat++
		}
	}
	return t
}

func usd(pts float64, contracts int) float64 { return pts * pointValue * float64(contracts) }

func (r *report) verdicts(st pep.Style) map[string]int {
	m := map[string]int{}
	for _, l := range r.lines[st] {
		if l.Verdict == "NO_TRADE" {
			continue
		}
		m[l.Verdict]++
	}
	return m
}

func (r *report) summaryText() string {
	var b strings.Builder
	for _, st := range []pep.Style{pep.StyleA, pep.StyleE} {
		t := tallyOf(r.lines[st])
		v := r.verdicts(st)
		fmt.Fprintf(&b, "style %s: traded %d days (W%d L%d flat%d), gross 6 MNQ %.0f, verdicts %v, no-data days with a PDF row: %d\n",
			st, t.traded, t.wins, t.losses, t.flat, usd(t.gross, 6), v, r.pdfNoData(st))
	}
	return b.String()
}

func (r *report) pdfNoData(st pep.Style) int {
	n := 0
	for _, l := range r.lines[st] {
		if l.PDF != nil && l.NoData {
			n++
		}
	}
	return n
}

func f2(x float64) string { return fmt.Sprintf("%.2f", x) }
func f0(x float64) string { return fmt.Sprintf("%.0f", x) }
func hm(ms int64) string  { return clockMs(ms) }
func orDash(s string) string {
	if s == "" {
		return "-"
	}
	return s
}

func (r *report) render(perDay bool) string {
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }
	w("# pep backtest vs the owner's PDF (data tables)\n\n")
	w("Generated by `go run ./cmd/pep-backtest` (kernel/pep, the same Evaluate the live loop calls). Range %s .. %s.\n\n", r.from, r.to)
	w("## Method\n\n")
	w("- Source: stored MNQ 1m bars from a READ-ONLY copy of data.db. Contract rows present: %s.\n", r.sources)
	w("- `historical_import` rows shifted by %d ms (they are close-stamped; verified against rows that exist twice).\n", r.shift)
	w("- Per day the contract with the most bars in 08:30-15:00 CT is used; the evaluator is handed the last %s closed 1m bars at every closed 1m bar from the box end to 15:00 CT.\n", r.window)
	w("- 2m candles: built inside kernel/pep from 1m on CT-even minutes; America/Chicago zoneinfo; $1 round trip per contract; same-bar stop before target; flat at the last price before 15:00 CT; a tape that ends early closes at its last price (the PDF's CUTOFF_PROXY).\n")
	a, e := r.cfgs[pep.StyleA], r.cfgs[pep.StyleE]
	w("- Fill convention: a stop fills on a %s; a target fills on a %s.\n", map[bool]string{false: "touch", true: "trade-through (strictly beyond)"}[r.opts.StopThrough], map[bool]string{false: "touch", true: "trade-through (strictly beyond)"}[r.opts.TargetThrough])
	w("- Style A: box %d min from %02d:%02d CT, SL %.2f x box, TP %.2f x box, one bar through both edges = `%s`.\n", a.A.BoxMinutes, a.BoxStartMin/60, a.BoxStartMin%60, a.A.SLFraction, a.A.TPFraction, a.A.BothEdges)
	w("- Style E: box %d min, EMA%d on %dm candles (source `%s`), SL %.2f x box rounded outward to %.2f, TP %.2f x box, warm-up %d candles.\n\n", e.E.BoxMinutes, e.E.EMAPeriod, e.E.EMATFMin, e.E.Source, e.E.SLFraction, e.TickSize, e.E.TPFraction, e.WarmupCandles())

	for _, st := range []pep.Style{pep.StyleA, pep.StyleE} {
		ls := r.lines[st]
		t := tallyOf(ls)
		pdf := r.pdf[st]
		var pdfG float64
		for _, p := range pdf {
			pdfG += p.Gross
		}
		w("## Style %s: summary\n\n", st)
		w("| | this run | PDF (6 MNQ ledger) |\n|---|---|---|\n")
		w("| days with a trade | %d | %d |\n", t.traded, len(pdf))
		w("| winners / losers / flat | %d / %d / %d | |\n", t.wins, t.losses, t.flat)
		w("| exits TP / SL / FLAT / DATA_END | %d / %d / %d / %d | |\n", t.byExit[pep.ExitTP], t.byExit[pep.ExitSL], t.byExit[pep.ExitFlat], t.byExit[pep.ExitDataEnd])
		w("| gross USD, 6 MNQ | %s | %s |\n", f0(usd(t.gross, 6)), f0(pdfG))
		w("| gross USD, 3 MNQ | %s | |\n", f0(usd(t.gross, 3)))
		w("| fees at $1 RT/contract, 6 / 3 MNQ | %d / %d | |\n", t.traded*6, t.traded*3)
		w("| net USD, 6 MNQ | %s | |\n", f0(usd(t.gross, 6)-float64(t.traded*6)))
		w("| net USD, 3 MNQ | %s | |\n\n", f0(usd(t.gross, 3)-float64(t.traded*3)))
		w("The PDF totals are for an ACCOUNT-MODELLED run (cooldown days skipped, breach days truncated); this run is the raw rule on every day with data, so totals differ by construction. Compare day by day below.\n\n")

		v := r.verdicts(st)
		var keys []string
		for k := range v {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		w("Day verdicts: ")
		for _, k := range keys {
			w("%s=%d  ", k, v[k])
		}
		w("\n\n")
		// common set: both traded, PDF row not an account-breach day
		var cm, cp float64
		n := 0
		for _, l := range ls {
			if l.PDF != nil && l.Mine.Traded && !strings.Contains(l.PDF.Result, "BREACH") {
				cm += l.Mine.GrossUSD(6, pointValue)
				cp += l.PDF.Gross
				n++
			}
		}
		w("Common days (both traded, PDF not a breach day): %d. Gross 6 MNQ: this run %s, PDF %s, difference %s.\n\n", n, f0(cm), f0(cp), f0(cm-cp))

		if len(t.refusals) > 0 {
			var rk []string
			for k := range t.refusals {
				rk = append(rk, k)
			}
			sort.Strings(rk)
			w("Days with data where this run did NOT trade, by refusal: ")
			for _, k := range rk {
				w("%s=%d  ", k, t.refusals[k])
			}
			w("\n\n")
		}
		var missing []string
		for _, l := range ls {
			if l.PDF != nil && l.NoData {
				missing = append(missing, l.Date)
			}
		}
		w("PDF days with NO bars in the DB (%d): %s\n\n", len(missing), orDash(strings.Join(missing, ", ")))

		if perDay {
			w("### Style %s: day by day (gross USD at 6 MNQ)\n\n", st)
			w("| date | PDF res | PDF gross | mine res | mine gross | box mine | box PDF-implied | side | entry | verdict | note |\n|---|---|---|---|---|---|---|---|---|---|---|\n")
			for _, l := range ls {
				if l.PDF == nil && !l.Mine.Traded {
					continue
				}
				pr, pg := "-", "-"
				if l.PDF != nil {
					pr, pg = l.PDF.Result, f0(l.PDF.Gross)
				}
				mr, mg, side, entry := "-", "-", "-", "-"
				if l.Mine.Traded {
					mr, mg, side, entry = string(l.Mine.ExitKind), f0(l.Mine.GrossUSD(6, pointValue)), string(l.Mine.Side), f2(l.Mine.Entry)
				} else if l.NoData {
					mr = "NO_DATA"
				} else {
					mr = l.Mine.Refusal
				}
				bm, bp := "-", "-"
				if l.Mine.Box.Drawn {
					bm = f2(l.Mine.Box.Size)
				}
				if l.PDFBoxPts > 0 {
					bp = f2(l.PDFBoxPts)
				}
				w("| %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |\n", l.Date, pr, pg, mr, mg, bm, bp, side, entry, l.Verdict, l.Note)
			}
			w("\n")
		}
	}
	return b.String()
}

func (r *report) csv() string {
	var b strings.Builder
	b.WriteString("style,date,contract,traded,side,entry,stop,target,exit,exit_kind,gross_pts,box_size,entry_at,exit_at,refusal,pdf_result,pdf_gross6,verdict\n")
	for _, st := range []pep.Style{pep.StyleA, pep.StyleE} {
		for _, l := range r.lines[st] {
			pr, pg := "", ""
			if l.PDF != nil {
				pr, pg = l.PDF.Result, f0(l.PDF.Gross)
			}
			m := l.Mine
			fmt.Fprintf(&b, "%s,%s,%q,%t,%s,%.2f,%.2f,%.2f,%.2f,%s,%.2f,%.2f,%d,%d,%s,%s,%s,%s\n",
				st, l.Date, l.Contract, m.Traded, m.Side, m.Entry, m.Stop, m.Target, m.Exit, m.ExitKind, m.GrossPts, m.Box.Size,
				m.EntryAt, m.ExitAt, m.Refusal, pr, pg, l.Verdict)
		}
	}
	return b.String()
}

