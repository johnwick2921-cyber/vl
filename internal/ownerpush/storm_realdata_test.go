func TestRealStopWidenRefusalsWouldHaveToldTheOwnerTwice(t *testing.T) {
	f := &flaky{}
	p, c := newClocked(f.send)
	var firedAtID []int64
	for _, r := range realStopWidenRefusals {
		c.mu.Lock()
		c.t = time.UnixMilli(r.tsMs)
		c.mu.Unlock()
		if p.NoteRefusal(Refusal{Class: ClassStopWiden, TraderID: "live-trader", Subject: "MNQ LONG", Detail: "new stop 29032.00 would widen from 29181.00"}) {
			firedAtID = append(firedAtID, r.id)
		}
	}
	p.Flush()
	if len(firedAtID) != 2 || firedAtID[0] != 316927 || firedAtID[1] != 341836 {
		t.Fatalf("want 2 episode pushes at log_events ids 316927 and 341836, got %v", firedAtID)
	}
	if n := len(f.sent()); n != 2 {
		t.Fatalf("want 2 messages delivered, got %d: %q", n, f.sent())
	}
}
